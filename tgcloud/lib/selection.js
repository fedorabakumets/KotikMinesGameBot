/**
 * @fileoverview Двухшаговый выбор режима игры и сложности с краткими правилами.
 */
import { button } from './view.js';
import { LEVELS } from './engine.js';
/** Описание режимов и действий запуска выбранной партии. */
const MODES = {
  /** Режим накопления очков с досрочным завершением. */
  risk: { title: '💎 Мины — Забрать', action: 'risk', rules: 'Открывай клетки по одной: каждая безопасная даёт 10 очков.\n💰 «Забрать» сохраняет очки и завершает раунд. Мина обнулит только текущий раунд.' },
  /** Классический сапёр с возможностью отмечать мины. */
  classic: { title: '🚩 Сапёр с флажками', action: 'new', rules: 'Открой все безопасные клетки. Цифры показывают соседние мины.\nОтмечай предполагаемые мины флажками.' },
  /** Классический сапёр без переключения режима. */
  plain: { title: '👆 Сапёр без флажков', action: 'plain', rules: 'Открой все безопасные клетки. Цифры показывают соседние мины.\nНажатие сразу открывает клетку, флажков нет.' },
};

/**
 * Создаёт главный экран выбора игры.
 * @returns {object} Текст и клавиатура режимов.
 */
export function gamesMenu() {
  return { text: '💣 Мины\n\nВыбери, как играть:\n\n💎 Забрать — собирай очки и решай, когда остановиться.\n🚩 Сапёр — находи безопасные клетки и отмечай мины.\n👆 Без флажков — сапёр с простым управлением.',
    reply_markup: { inline_keyboard: [
      [button('💎 Играть с «Забрать»', 'choose:risk')],
      [button('🚩 Сапёр с флажками', 'choose:classic')],
      [button('👆 Сапёр без флажков', 'choose:plain')],
      [button('📊 Моя статистика', 'stats')],
    ] } };
}

/**
 * Создаёт отдельный экран сложности для выбранного режима.
 * @param {string} mode - Выбранный режим игры.
 * @returns {object} Правила режима и три кнопки сложности.
 */
export function difficultyMenu(mode) {
  const selected = MODES[mode];
  if (!selected) return gamesMenu();
  const names = ['🙂 Легко', '😎 Средне', '🔥 Сложно'];
  return { text: `${selected.title}\n\n${selected.rules}\n\nПоле 5×5. Первый ход безопасный.\nВыбери сложность:`,
    reply_markup: { inline_keyboard: [
      ...LEVELS.map((count, index) => [button(`${names[index]} · ${count} мин`, `${selected.action}:${count}`)]),
      [button('⬅️ Выбор игры', 'games')],
    ] } };
}
